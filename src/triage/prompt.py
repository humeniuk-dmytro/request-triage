DEDUPE_SYSTEM_PROMPT = """\
Ти отримуєш список запитів до AI-юніту: id та коротка суть кожного. Знайди \
пари, де другий запит просить по суті те саме, що вже просить перший.

Дубль — це та сама робота: той самий результат для того самого процесу. \
Схожа тематика дублем не є: два різні звіти по одній системі — це дві задачі.

Для кожної знайденої пари поверни `duplicate_id` (пізніший запит) та \
`original_id` (той, що надійшов раніше). Якщо дублів немає — порожній список.\
"""

DEDUPE_RESPONSE_SCHEMA: dict = {
    "type": "OBJECT",
    "required": ["duplicates"],
    "properties": {
        "duplicates": {
            "type": "ARRAY",
            "items": {
                "type": "OBJECT",
                "required": ["duplicate_id", "original_id", "reason"],
                "propertyOrdering": ["reason", "duplicate_id", "original_id"],
                "properties": {
                    "reason": {"type": "STRING", "description": "Чому це та сама робота."},
                    "duplicate_id": {"type": "STRING"},
                    "original_id": {"type": "STRING"},
                },
            },
        }
    },
}


def prompt_fingerprint() -> str:
    """Хеш усіх промптів — потрапляє в маніфест прогону.

    Різні результати на однакових даних пояснюються або зміною моделі, або
    зміною промпту. Хеш робить друге перевірюваним замість «здається, я щось
    там правив».
    """
    payload = "\n".join([SYSTEM_PROMPT, DEDUPE_SYSTEM_PROMPT])
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]
